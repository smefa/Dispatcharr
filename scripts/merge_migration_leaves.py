#!/usr/bin/env python3
"""Add Django merge migrations where an upstream merge left several leaves.

The fork adds its own migrations (e.g. core 0033_outputprofile_xc_path).
Whenever upstream adds migrations to the same app, the merged graph has two
leaf nodes and Django refuses to migrate. This writes the same kind of merge
migration ``makemigrations --merge`` would, without needing Django installed.

Usage: merge_migration_leaves.py <repo root> <release tag>
Prints the paths of created files, one per line.
"""

import ast
from collections import Counter
from pathlib import Path
import re
import sys

MIGRATION = re.compile(r"^(\d+)_\w+\.py$")


def _dependencies(path):
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "Migration":
            for statement in node.body:
                if (
                    isinstance(statement, ast.Assign)
                    and any(getattr(t, "id", None) == "dependencies" for t in statement.targets)
                ):
                    return [
                        tuple(ast.literal_eval(element))
                        for element in statement.value.elts
                        if isinstance(element, ast.Tuple)
                    ]
            return []
    raise ValueError(f"{path} has no Migration class")


def merge_directory(directory, tag):
    names = sorted(p.stem for p in directory.iterdir() if MIGRATION.match(p.name))
    if not names:
        return None
    edges = [
        edge
        for name in names
        for edge in _dependencies(directory / f"{name}.py")
        if edge[1] in names
    ]
    if not edges:
        return None
    # Other apps may share names such as 0001_initial; the app's own label
    # is the one on almost every edge, since each migration follows another.
    label = Counter(app_label for app_label, _ in edges).most_common(1)[0][0]
    referenced = {dependency for app_label, dependency in edges if app_label == label}
    leaves = [name for name in names if name not in referenced]
    if len(leaves) < 2:
        return None
    number = max(int(MIGRATION.match(f"{name}.py").group(1)) for name in names) + 1
    slug = re.sub(r"\W", "_", tag.lstrip("v"))
    target = directory / f"{number:04d}_merge_upstream_{slug}.py"
    dependencies = "".join(f"        ({label!r}, {leaf!r}),\n" for leaf in leaves)
    target.write_text(
        f"# Merges the fork's migrations with upstream {tag}.\n"
        "# Generated by scripts/merge_migration_leaves.py.\n\n"
        "from django.db import migrations\n\n\n"
        "class Migration(migrations.Migration):\n\n"
        f"    dependencies = [\n{dependencies}    ]\n\n"
        "    operations = []\n",
        encoding="utf-8",
    )
    return target


def main(root, tag):
    root = Path(root)
    created = []
    for directory in sorted(root.glob("**/migrations")):
        if "node_modules" in directory.parts or not directory.is_dir():
            continue
        target = merge_directory(directory, tag)
        if target:
            created.append(target)
            print(target.relative_to(root).as_posix())
    return created


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
